"""Deterministic reStructuredText generated from schemas and conventions (DOC-1, DOC-3)."""

from __future__ import annotations

import importlib
import inspect
import json
import pkgutil

from pydantic import BaseModel

import prophetovol
from prophetovol.core.conventions import CONVENTIONS
from prophetovol.registry.catalog import all_registries


def _heading(title: str, char: str = "=") -> str:
    """A reStructuredText heading."""
    return title + "\n" + char * len(title) + "\n\n"


def _schema_block(schema: dict) -> str:
    """Render the complete schema, including nested definitions and constraints."""
    return ".. code-block:: json\n\n" + "\n".join(
        "   " + line for line in json.dumps(schema, indent=2, ensure_ascii=False, sort_keys=True).splitlines()) + "\n\n"


def reference_documents() -> dict[str, str]:
    """Render every reference file from the current package without writing anything.

    :returns: File names mapped to UTF-8-ready text, without timestamps or local paths.
    """
    notice = ".. Generated by prophetovol docs generate. Do not edit by hand.\n\n"
    conventions = notice + _heading("Internal conventions")
    for convention in CONVENTIONS:
        conventions += _heading(f"{convention.id}: {convention.title}", "-") + convention.statement + "\n\n"
    models = {}
    for info in sorted(pkgutil.walk_packages(prophetovol.__path__, "prophetovol."), key=lambda item: item.name):
        module = importlib.import_module(info.name)
        for name, obj in vars(module).items():
            if (not name.startswith("_") and inspect.isclass(obj) and issubclass(obj, BaseModel)
                    and obj.__module__ == module.__name__):
                models[f"{module.__name__}.{name}"] = obj
    schemas = notice + _heading("Model reference")
    schemas += "Each schema includes field descriptions, defaults, required fields, units and constraints.\n\n"
    for name, model in sorted(models.items()):
        schemas += _heading(name, "-") + _schema_block(model.model_json_schema())
    registries = notice + _heading("Registry reference")
    for registry in all_registries():
        registries += _heading(registry.kind, "-") + registry.description + "\n\n"
        for name in registry.names():
            item = registry.describe(name)
            registries += _heading(item.name, "~") + item.description + "\n\nVersion: ``" + item.version + "``.\n\n"
            registries += _schema_block(item.params_schema)
    index = notice + _heading("ProphetoVol reference") + (
        "Generated from the package's pydantic models, registries and internal conventions.\n\n"
        ".. toctree::\n   :maxdepth: 2\n\n   conventions\n   models\n   registries\n")
    return {"index.rst": index, "conventions.rst": conventions, "models.rst": schemas, "registries.rst": registries}
